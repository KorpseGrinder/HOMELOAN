    VERIFICATION_STATUS VARCHAR2(20) DEFAULT 'PENDING',
    VERIFIED_BY VARCHAR2(50),
    VERIFIED_DATE TIMESTAMP,
    REMARKS VARCHAR2(500),
    CREATED_BY VARCHAR2(50) NOT NULL,
    CREATED_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    MODIFIED_BY VARCHAR2(50),
    MODIFIED_DATE TIMESTAMP,
    VERSION NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT FK_CUST_KYC_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID)
);

CREATE SEQUENCE SEQ_CUSTOMER_BANK_ACCOUNT_ID START WITH 1 INCREMENT BY 1;

CREATE TABLE CUSTOMER_BANK_ACCOUNT (
    BANK_ACCOUNT_ID NUMBER(19) DEFAULT SEQ_CUSTOMER_BANK_ACCOUNT_ID.NEXTVAL PRIMARY KEY,
    CUSTOMER_ID NUMBER(19) NOT NULL,
    BANK_NAME VARCHAR2(100) NOT NULL,
    BRANCH_NAME VARCHAR2(100),
    ACCOUNT_NUMBER VARCHAR2(255) NOT NULL,
    IFSC_CODE VARCHAR2(11) NOT NULL,
    ACCOUNT_TYPE VARCHAR2(20) NOT NULL,
    IS_PRIMARY NUMBER(1) DEFAULT 0,
    ACCOUNT_HOLDER_NAME VARCHAR2(200),
    CREATED_BY VARCHAR2(50) NOT NULL,
    CREATED_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    MODIFIED_BY VARCHAR2(50),
    MODIFIED_DATE TIMESTAMP,
    VERSION NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT FK_CUST_BANK_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES CUSTOMER(CUSTOMER_ID)
);
